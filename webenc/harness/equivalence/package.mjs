import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {unzipSync} from 'fflate';
import {createCavcPackage} from '../../src/cavc-package.js';
const job=process.argv[2];if(!job)throw new Error('Completed Wasm job required');
const data={files:{},manifest:JSON.parse(await readFile(path.join(job,'manifest.json'))),...JSON.parse(await readFile(path.join(job,'wasm-result.json')))};
data.discName=Object.keys(data.hashes).find(name=>name.endsWith('.iso'))?.slice(0,-4);
if(!data.discName)throw new Error('Completed browser ISO/CUE output required');
for(const name of ['HEADER.DAT','BODY.DAT','MOVIE.DAT','stage-sha256.tsv','playback-frames.tsv','preview.mp4','playback.wav',data.discName+'.iso',data.discName+'.cue'])data.files[name]=await readFile(path.join(job,'wasm-'+name));
const zip=createCavcPackage(data),files=unzipSync(zip);
for(const [name,bytes] of Object.entries(data.files))assert(Buffer.from(files[name]).equals(bytes),`${name}: ZIP changed generated bytes`);
assert(Buffer.concat([Buffer.from(files['HEADER.DAT']),Buffer.from(files['BODY.DAT'])]).equals(Buffer.from(files['MOVIE.DAT'])));
await writeFile(path.join(job,'browser-cavc-stream.zip'),zip);
console.log('SPA ZIP package preserves all completed Wasm stream bytes: PASS');
